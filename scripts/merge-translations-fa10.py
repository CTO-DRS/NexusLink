def deep_merge(dst: dict, src: dict) -> dict:
    for k, v in src.items():
        if isinstance(v, dict) and isinstance(dst.get(k), dict):
            deep_merge(dst[k], v)
        else:
            dst[k] = v
    return dst


def main():
    for path, sections, nav, common in [
        (AR_PATH, AR, AR_NAV, AR_COMMON),
        (EN_PATH, EN, EN_NAV, EN_COMMON),
    ]:
        with io.open(path, encoding="utf-8") as f:
            data = json.load(f)
        deep_merge(data, sections)
        deep_merge(data.setdefault("nav", {}), nav)
        deep_merge(data.setdefault("common", {}), common)
        with io.open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        # تحقق التطابق: عدد مفاتيح sec/onb/lock/lost متساوٍ
        print(path.split("/")[-1], "→ nav:", "security" in data["nav"],
              "| sec:", len(data["sec"]), "| onb:", len(data["onb"]),
              "| lock:", len(data["lock"]), "| lost:", len(data["lost"]))


if __name__ == "__main__":
    main()
