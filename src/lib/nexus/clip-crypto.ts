// عقد §58 — قفل الخزنة الساكن (CLIP-AT-REST) — قفص ProdClip النقي
// ============================================================
// إغلاق الحد الموروث من §50 حرفيًا: «من يملك الوصول للقاعدة الخام يرى كل شيء
// (التشفير الكامل للخزنة عمل لاحق معلن)» — وأُعيد إعلانه حدًّا باقيًا في §57.
// محتوى خزنة الحافظة (ProdClip.content) لا يُكتب في قاعدة SQLite نصًّا عاريًا
// أبدًا: كل محتوى يُختم AES-256-GCM بقفص §58 (علامة clip.at-rest) بمفتاح
// محلي 32 بايت مرسوخ DesktopSetting (نمط §34.ب/§54/§57) لا يغادر الجهاز
// ولا يعود في أي API. من يسرق ملف القاعدة يرى مغلفات لا أسرار.
//
// مقابل المنافسين مباشرة:
//  - Win+V / سجل حافظة النظام: نص عاري في ملف النظام — هنا مغلف بمصادقة GCM.
//  - Pushbullet/KDE: السجل عند وسيط أو نصًّا عاريًا محليًا — هنا القاعدة
//    مغلفة والبث الشبكي كان مشفرًا سلفًا (F6 قناة 3009).
//
// حدود صادقة (§58.حدود):
//  - القفل للقرص لا للذاكرة ولا للعرض: القوائم والبحث والكشف تحتاج النص
//    الصريح فيم يُفك عند حدود القرص حصرًا (نمط §57 المعلن).
//  - المفتاح في قاعدة الجهاز نفسها — من يملك القرص كله مع جلسة كاملة
//    يستطيع الفتح؛ القفل يرفع كلفة سرقة ملف القاعدة المعزول (نعلنها).
//  - البيانات الوصفية (id/kind/size/mode/التواريخ/الحساسية/التدبيس) تبقى
//    نصًّا: التقليم والفرز والإحصاء لا يحتاجون فك الختم وفشل الفك لا يعمي
//    القائمة — يُسقط المتأثر حصرًا بصدق (نمط §57).
//  - السجلات القديمة النص العاري تبقى مقروءة وتُختم عند أول كتابة تالية
//    (ترحيل صامت) + فعل «ختم السجل» يختم كل شيء فورًا بإرادة صريحة.
//
// حساب السقف (موثق — درس §57.أ12 المطبق): سقف المحتوى التعاقدي 4,000,000
// محرف UTF-16 (حد مسارات الكتابة الحرفي) — أسوأ حالة عربي BMP بثلاث بايتات
// UTF-8 لكل محرف = 12,000,000 بايت → base64 (×4/3) = 16,000,000 محرفًا
// + مغلف JSON ≈ 140 — السقف 16,800,000 بهامش أمان، دفاع في العمق.

import { createAtRestCage } from "./at-rest-cage"

export const CLIP_AT_REST_VERSION = 1
/** علامة قفص الخزنة — تميز مغلف §58 في عمود content عن النص العاري القديم
 *  وعن مغلفات §57 (كل قفص بعلامته فلا التباس شكل أبدًا) */
export const CLIP_AT_REST_MARKER = "clip.at-rest"
/** سقف المحتوى التعاقدي لمسارات الكتابة (نفس حد §11 الحرفي) */
export const CLIP_CONTENT_MAX = 4_000_000
/** سقف المغلف النصي — الحساب أعلاه */
export const CLIP_AT_REST_SEALED_MAX = 16_800_000

/** قفص §58 — نفس محرك §57 الموحد بعلامة الخزنة وسقفها — وأدنى قناغة 1 بايت:
 *  GCM تدفقي فقناغة رمز OTP الستّي 6 بايتات شرعية (درس مُقاس: حرس §57 الـ16
 *  كان يُسقط كل محتوى قصير تحت 16 بايت — رموز الدخول تحديدًا — بصدق شكلي
 *  لكن بإسقاط ظالم؛ هنا الحرس 1 والفارغ مستبعد بأنه لا يُختم أصلًا) */
export const clipCage = createAtRestCage({
  marker: CLIP_AT_REST_MARKER,
  version: CLIP_AT_REST_VERSION,
  sealedMax: CLIP_AT_REST_SEALED_MAX,
  minCtBytes: 1,
})
